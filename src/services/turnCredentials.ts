/**
 * TURN credentials service
 *
 * Supplies ICE servers for P2P connections from the user's TURN credentials.
 * Owned by P2PManager and lazy: nothing is subscribed to or generated until
 * P2P first asks for ICE servers, so single-player games never touch TURN.
 */

import type { FunctionReturnType } from "convex/server";
import { api } from "@wvdsh/api";
import { WavedashManager } from "./manager";
import { logger } from "../utils/logger";

type TurnCredentials = NonNullable<
  FunctionReturnType<typeof api.sdk.turnCredentials.get>
>;

// Treat TURN credentials this close to expiring as needing a refresh
const EXPIRY_BUFFER_MS = 1000 * 60 * 60;
// A refresh, retries included, settles within this window
const REFRESH_TIMEOUT_MS = 15_000;
// Backoff between retries of a failed refresh attempt
const RETRY_BASE_DELAY_MS = 1_000;
const RETRY_MAX_DELAY_MS = 4_000;

export class TurnCredentialsManager extends WavedashManager {
  // Kept current by a subscription once P2P first asks for ICE servers:
  // undefined until its first result, null when the user has none.
  private credentials: TurnCredentials | null | undefined = undefined;
  private unsubscribe: (() => void) | null = null;
  // Called on every subscription result, or with the subscription's error
  private listeners = new Set<(error?: unknown) => void>();
  private refreshing: Promise<void> | null = null;

  destroy(): void {
    this.unsubscribe?.();
    this.unsubscribe = null;
    this.credentials = undefined;
  }

  /**
   * Get ICE servers from the user's TURN credentials, refreshing them first if
   * they're missing or close to expiring. Concurrent calls share one refresh.
   * Never throws: a refresh that keeps failing gives up after
   * REFRESH_TIMEOUT_MS, and this returns whatever credentials there are, or
   * null if there are none.
   */
  async getIceServers(): Promise<RTCIceServer[] | null> {
    if (!this.hasFreshCredentials()) {
      this.refreshing ??= this.refreshWithRetries().finally(() => {
        this.refreshing = null;
      });
      await this.refreshing;
    }
    return this.credentials?.iceServers ?? null;
  }

  private hasFreshCredentials(): boolean {
    return (
      !!this.credentials &&
      this.credentials.expiresAt > Date.now() + EXPIRY_BUFFER_MS
    );
  }

  /** Retries failed refresh attempts with backoff until the deadline. */
  private async refreshWithRetries(): Promise<void> {
    const deadline = Date.now() + REFRESH_TIMEOUT_MS;
    for (let attempt = 0; ; attempt++) {
      try {
        await this.refresh(deadline);
        return;
      } catch (error) {
        const delay = Math.min(
          RETRY_BASE_DELAY_MS * 2 ** attempt,
          RETRY_MAX_DELAY_MS
        );
        if (Date.now() + delay >= deadline) {
          logger.error(`Giving up on refreshing TURN credentials: ${error}`);
          return;
        }
        logger.warn(
          `Failed to refresh TURN credentials, retrying in ${delay}ms: ${error}`
        );
        await new Promise((resolve) => setTimeout(resolve, delay));
      }
    }
  }

  /**
   * Credentials are read through a subscription (a query the backend can
   * cache per user) and generated by a separate mutation, which schedules the
   * generation and lets the subscription deliver the result. Rejects on any
   * failure, or once `deadline` passes.
   */
  private async refresh(deadline: number): Promise<void> {
    this.subscribe();
    await this.waitFor((credentials) => credentials !== undefined, deadline);
    if (this.hasFreshCredentials()) return;

    const previousExpiresAt = this.credentials?.expiresAt ?? 0;
    const generating = await this.beforeDeadline(
      this.sdk.convexClient.mutation(api.sdk.turnCredentials.ensureFresh, {}),
      deadline
    );
    // The backend's clock decides: if it generated nothing, what we have is
    // good to use even if this device's clock says otherwise.
    if (!generating) return;

    await this.waitFor(
      (credentials) =>
        !!credentials && credentials.expiresAt > previousExpiresAt,
      deadline
    );
  }

  private subscribe(): void {
    if (this.unsubscribe) return;

    this.unsubscribe = this.sdk.convexClient.onUpdate(
      api.sdk.turnCredentials.get,
      {},
      (credentials) => {
        this.credentials = credentials;
        for (const listener of [...this.listeners]) listener();
      },
      (error) => {
        logger.error(`TURN credentials subscription error: ${error}`);
        // Convex reports an error only when the query result changes, so a
        // retry waiting on this subscription could wait forever. Drop it so
        // the next refresh resubscribes and gets the query's current result.
        this.unsubscribe?.();
        this.unsubscribe = null;
        for (const listener of [...this.listeners]) listener(error);
      }
    );
  }

  /**
   * Resolves once the subscribed credentials satisfy `isReady`. Rejects if
   * the subscription errors, or once `deadline` passes.
   */
  private waitFor(
    isReady: (credentials: TurnCredentials | null | undefined) => boolean,
    deadline: number
  ): Promise<void> {
    return new Promise((resolve, reject) => {
      const listener = (error?: unknown) => {
        if (error === undefined && !isReady(this.credentials)) return;
        clearTimeout(timer);
        this.listeners.delete(listener);
        if (error === undefined) resolve();
        else reject(error);
      };
      const timer = setTimeout(
        () => listener(new Error("Timed out waiting for TURN credentials")),
        deadline - Date.now()
      );
      this.listeners.add(listener);
      listener();
    });
  }

  /** Rejects if `promise` hasn't settled by `deadline`. */
  private beforeDeadline<T>(promise: Promise<T>, deadline: number): Promise<T> {
    let timer: ReturnType<typeof setTimeout> | undefined;
    const timeout = new Promise<never>((_, reject) => {
      timer = setTimeout(
        () => reject(new Error("Timed out generating TURN credentials")),
        deadline - Date.now()
      );
    });
    return Promise.race([promise, timeout]).finally(() => clearTimeout(timer));
  }
}
